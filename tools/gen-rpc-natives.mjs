// Generator for the context-routed (RPC) native table.
//
// Reads the CFX RPC native spec vendored at
// `crates/baston-scripting/assets/rpc_natives.json` and emits the Rust table
// consumed by `crates/baston-scripting/src/extensions/rpc_natives/`.
//
//   node tools/gen-rpc-natives.mjs
//   cargo fmt --all
//
// Only `"type": "ctx"` entries are emitted. The `"entity"` and `"object"`
// entries of the spec are native *constructors* (CREATE_PED, ADD_BLIP_*): they
// need a server-side entity/object registry to hand a handle back to the
// script, which is a separate piece of work, so they are deliberately skipped
// here rather than half-supported.
//
// The spec is data, not code: hashes and context indices are taken from the
// JSON verbatim so this file never has to be edited when the spec is refreshed
// from a newer FiveM artifact.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(
  repoRoot,
  "crates/baston-scripting/assets/rpc_natives.json"
);
const outPath = join(
  repoRoot,
  "crates/baston-scripting/src/extensions/rpc_natives/table.rs"
);

/** Map a spec `ctx.type` onto an `RpcContext` variant. */
function context(ctx) {
  switch (ctx.type) {
    case "Entity":
      return `RpcContext::Entity { idx: ${ctx.idx} }`;
    case "Player":
      return `RpcContext::Player { idx: ${ctx.idx} }`;
    case "ObjRef":
      return `RpcContext::ObjectRef { idx: ${ctx.idx} }`;
    case "ObjDel":
      return `RpcContext::ObjectDelete { idx: ${ctx.idx} }`;
    default:
      throw new Error(`unknown ctx type ${ctx.type} (spec changed?)`);
  }
}

const spec = JSON.parse(readFileSync(specPath, "utf8"));
const ctxNatives = spec
  .filter((entry) => entry.type === "ctx")
  // Sorted by name so the Rust side can binary-search the table.
  .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

const entries = ctxNatives
  .map((entry) => {
    const hash = entry.hash.replace(/^0x/i, "").toUpperCase();
    if (!/^[0-9A-F]{1,16}$/.test(hash)) {
      throw new Error(`${entry.name}: unexpected hash ${entry.hash}`);
    }
    return [
      "    RpcNative {",
      `        name: ${JSON.stringify(entry.name)},`,
      `        hash: 0x${hash},`,
      `        context: ${context(entry.ctx)},`,
      `        arg_count: ${entry.args.length},`,
      "    },",
    ].join("\n");
  })
  .join("\n");

const source = `//! Generated by \`node tools/gen-rpc-natives.mjs\` — do not edit by hand.
//!
//! Source: \`crates/baston-scripting/assets/rpc_natives.json\`, vendored
//! verbatim from the FiveM client artifact **35419**
//! (\`citizen/scripting/rpc_natives.json\`). Refresh the JSON from a newer
//! artifact and re-run the generator to update this table.

use super::{RpcContext, RpcNative};

/// Every \`"type": "ctx"\` entry of the CFX RPC spec (${ctxNatives.length} natives),
/// sorted by name so [\`super::lookup\`] can binary-search it.
pub(super) static CTX_NATIVES: &[RpcNative] = &[
${entries}
];
`;

writeFileSync(outPath, source);
console.log(`wrote ${ctxNatives.length} ctx natives to ${outPath}`);
